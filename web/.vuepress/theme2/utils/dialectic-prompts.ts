export const MIN_SHORT_LENGTH = 5;
export const MIN_LONG_LENGTH = 10;

export function validateStep(index: number, input: StepInput): boolean {
  if (!input) return false;
  switch (index) {
    case 0:
      return (input.value || '').trim().length >= MIN_SHORT_LENGTH;
    case 1:
      return (input.value || '').trim().length >= MIN_LONG_LENGTH;
    case 2:
      return !!(input.level && (input.note || '').trim().length > 0);
    case 3:
      return (input.value || '').trim().length >= MIN_LONG_LENGTH;
    case 4:
      return (
        (input.view1 || '').trim().length >= MIN_SHORT_LENGTH &&
        (input.view2 || '').trim().length >= MIN_SHORT_LENGTH
      );
    case 5:
      return (input.value || '').trim().length >= MIN_SHORT_LENGTH;
    case 6:
      return (input.value || '').trim().length >= MIN_SHORT_LENGTH;
    case 7:
      return (input.value || '').trim().length >= MIN_SHORT_LENGTH;
    case 8:
      return (input.value || '').trim().length >= MIN_SHORT_LENGTH;
    default:
      return false;
  }
}

